-- Proposed Supabase PostgreSQL schema and RLS rules for Neighborhood Listing Platform.
-- This file is committed evidence of policy source code, NOT proof that it was applied.
-- Apply to a development Supabase database, then collect actual API output.
CREATE TABLE IF NOT EXISTS public.properties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES auth.users(id),
  title text NOT NULL,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published'))
);

ALTER TABLE public.properties ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS properties_read ON public.properties;
CREATE POLICY properties_read ON public.properties
FOR SELECT TO anon, authenticated
USING (
  status = 'published'
  OR owner_id = (SELECT auth.uid())
  OR (SELECT auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

DROP POLICY IF EXISTS properties_insert ON public.properties;
CREATE POLICY properties_insert ON public.properties
FOR INSERT TO authenticated
WITH CHECK (owner_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS properties_update ON public.properties;
CREATE POLICY properties_update ON public.properties
FOR UPDATE TO authenticated
USING (owner_id = (SELECT auth.uid()))
WITH CHECK (owner_id = (SELECT auth.uid()));

-- No DELETE policy: regular clients including a custom-claim admin cannot delete.
-- A trusted service_role credential bypasses RLS; never expose it to a browser.
-- API grants are also required in addition to these RLS policies.
